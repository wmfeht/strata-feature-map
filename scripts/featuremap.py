@dataclass(frozen=True)
class Issue:
    level: str
    where: str
    message: str

    def __str__(self) -> str:
        return f"{self.level}: {self.where}: {self.message}"


@dataclass
class Node:
    id: str
    path: str
    meta: dict
    sections: dict[str, str]
    behavior: list[str] = field(default_factory=list)
    history: list[dict] = field(default_factory=list)

    @property
    def depth(self) -> int:
        return self.id.count("/") + 1

    def listed(self, key: str) -> list[str]:
        value = self.meta.get(key)
        return [v for v in value if isinstance(v, str)] if isinstance(value, list) else []

    def patterns(self) -> list[str]:
        return self.listed("code") + self.listed("tests")

    def reviewed_at(self) -> str | None:
        sha = self.meta.get("reviewed_at")
        return sha if isinstance(sha, str) and SHA_RE.fullmatch(sha) else None


@dataclass
class Tree:
    root: Path
    nodes: dict[str, Node]
    issues: list[Issue]

    def ordered(self) -> list[str]:
        return sorted(self.nodes, key=id_key)

    def subtree(self, node_id: str) -> list[str]:
        return [n for n in self.ordered() if n == node_id or n.startswith(node_id + "/")]

    def children(self, node_id: str) -> list[str]:
        return [n for n in self.subtree(node_id) if n.count("/") == node_id.count("/") + 1]

    def ancestors(self, node_id: str) -> list[str]:
        parts = node_id.split("/")
        candidates = ("/".join(parts[:i]) for i in range(2, len(parts)))
        return [c for c in candidates if c in self.nodes]


