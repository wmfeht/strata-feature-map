def cmd_check(args: argparse.Namespace) -> int:
    lister = None if args.offline else Upstream(args.root, load_sources(args.root)).files
    issues = check(args.root, lister)
    for issue in issues:
        print(issue, file=sys.stderr)
    errors = sum(1 for i in issues if i.level == "error")
    counts = f"{len(load_tree(args.root).nodes)} features, {len(load_sweeps(args.root).sweeps)} sweeps"
    print(f"check: {counts}, {errors} errors, {len(issues) - errors} warnings")
    return 1 if errors else 0


def cmd_drift(args: argparse.Namespace) -> int:
    root = args.root
    sources = load_sources(root)
    repo = sources["upstream"]["repo"]
    base = args.since or sources.get("watermark")
    if not base:
        raise SystemExit("watermark is not set in sources.yaml; pass --since <sha> for a dry run")
    upstream = Upstream(root, sources)
    head = args.head or upstream.head()
    tree, scopes, dataset = load_tree(root), load_scopes(root), load_dataset(root)
    commits = upstream.log(base, head)
    numbers, direct = [], []
    for sha, subject in commits:
        m = PR_SUBJECT_RE.search(subject)
        if m:
            numbers.append(int(m.group(1) or m.group(2)))
        else:
            direct.append((sha, subject))
    missing = [n for n in numbers if n not in dataset]
    if missing:
        collect(root, repo, missing, dataset)
    new_prs = [(dataset[n], assign(tree, scopes, dataset[n])) for n in sorted(numbers) if n in dataset]
    stale: dict[str, list[dict]] = {}
    ranges: dict[str, set[str]] = {}
    for node_id, node in tree.nodes.items():
        sha = node.reviewed_at()
        if sha is None:
            continue
        if sha not in ranges:
            ranges[sha] = upstream.commits(sha, head)
        rows = [
            row
            for row in dataset.values()
            if row.get("merge_commit") in ranges[sha]
            and any(matches(p, f) for f in row.get("files") or [] for p in node.patterns())
        ]
        if rows:
            stale[node_id] = rows
    report = render_drift(repo, base, head, len(commits), new_prs, stale, tree, scopes, direct)
    if args.out:
        args.out.write_text(report)
    else:
        sys.stdout.write(report)
    return 0


def cmd_qa(args: argparse.Namespace) -> int:
    root = args.root
    sources = load_sources(root)
    upstream = sources.get("upstream") if isinstance(sources.get("upstream"), dict) else {}
    repo = upstream.get("repo", "lgse/strata")
    watermark = sources.get("watermark") if isinstance(sources.get("watermark"), str) else None
    tree, scopes, sweeps, dataset = load_tree(root), load_scopes(root), load_sweeps(root), load_dataset(root)
    if args.all or args.sweep:
        areas = sorted(sweeps.sweeps) if args.all else sorted(set(args.sweep))
        unknown = [a for a in areas if a not in sweeps.sweeps]
        if unknown:
            raise SystemExit("no such sweep: " + ", ".join(unknown))
        subject = "all sweeps" if args.all else "sweep " + ", ".join(f"`{a}`" for a in areas)
        plan = PlanInput(subject, args.head or watermark, None, [], None, areas, args.tier)
    else:
        pr, files, head = None, [], args.head
        if args.pr:
            pr_repo, number = parse_pr_ref(args.pr, repo)
            pr = dataset.get(number) if pr_repo == repo else None
            if pr is None:
                pr = next(fetch_prs(pr_repo, [number]), None)
            if pr is None:
                raise SystemExit(f"{pr_repo}#{number} was not found")
            pr = dict(pr, ref=f"{pr_repo}#{number}")
            files = pr.get("files") or []
            subject = f"{pr_repo}#{number} · {pr['title']}"
            head = head or pr.get("merge_commit") or pr.get("head_commit")
            owner = assign(tree, scopes, pr).node
            primary = sorted(touched(tree, files), key=id_key)
        elif args.files:
            text = sys.stdin.read() if args.files == "-" else Path(args.files).read_text()
            files = [line.strip() for line in text.splitlines() if line.strip()]
            subject = f"{len(files)} changed files"
            owner = assign(tree, scopes, {"files": files, "scope": None}).node
            primary = sorted(touched(tree, files), key=id_key)
        else:
            unknown = [n for n in args.node if n not in tree.nodes]
            if unknown:
                raise SystemExit("no such node: " + ", ".join(unknown))
            primary = sorted(set(args.node), key=id_key)
            subject = "node " + ", ".join(f"`{n}`" for n in primary)
            head = head or watermark
            owner = primary[0] if len(primary) == 1 else None
        reach = radius(tree, sweeps, primary, files, owner)
        if not reach.primary and not reach.forced:
            raise SystemExit("no node or trigger matches these files; nothing to plan:\n" + "\n".join(files))
        plan = PlanInput(subject, head, pr, files, reach, [], args.tier)
    text = render_plan(tree, sweeps, repo, plan)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
        print(f"qa: wrote {args.out}")
    else:
        sys.stdout.write(text)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    extract = sub.add_parser("extract", help="pull merged upstream PRs into data/prs.jsonl")
    extract.add_argument("--refresh", action="store_true", help="refetch PRs already in the dataset")
    sub.add_parser("index", help="regenerate README.md and index/")
    check_cmd = sub.add_parser("check", help="validate the feature tree")
    check_cmd.add_argument("--offline", action="store_true", help="skip the upstream path check")
    drift = sub.add_parser("drift", help="report upstream changes since the watermark")
    drift.add_argument("--since", help="base commit instead of the watermark")
    drift.add_argument("--head", help="head commit instead of upstream's branch head")
    drift.add_argument("--out", type=Path, help="write the report here instead of stdout")
    qa = sub.add_parser("qa", help="render a QA plan for a PR, a diff, a node, or a sweep")
    what = qa.add_mutually_exclusive_group(required=True)
    what.add_argument("--pr", help="PR number, or owner/repo#n for a fork PR")
    what.add_argument("--files", help="file with one changed path per line, or - for stdin")
    what.add_argument("--node", action="append", help="node id; repeatable")
    what.add_argument("--sweep", action="append", help="sweep (area) name; repeatable")
    what.add_argument("--all", action="store_true", help="every sweep, for a full parallel run")
    qa.add_argument("--tier", type=int, choices=(1, 2, 3), default=2, help="how far the blast radius expands (default 2)")
    qa.add_argument("--head", help="commit under test, when the input does not imply one")
    qa.add_argument("--out", type=Path, help="write the plan here instead of stdout")
    args = parser.parse_args(argv)
    commands = {"extract": cmd_extract, "index": cmd_index, "check": cmd_check, "drift": cmd_drift, "qa": cmd_qa}
    return commands[args.command](args)


