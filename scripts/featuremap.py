@dataclass
class Sweep:
    """One QA sweep: `qa/sweeps/<area>.md`, owning every node under `features/<area>/`."""

    area: str
    path: str
    meta: dict
    sections: dict[str, str]
    probes: dict[str | None, list[str]] = field(default_factory=dict)
    handoffs: list[tuple[str, str]] = field(default_factory=list)

    def listed(self, key: str) -> list[str]:
        value = self.meta.get(key)
        return [v for v in value if isinstance(v, str)] if isinstance(value, list) else []

    def reviewed_at(self) -> str | None:
        sha = self.meta.get("reviewed_at")
        return sha if isinstance(sha, str) and SHA_RE.fullmatch(sha) else None


@dataclass
class Sweeps:
    sweeps: dict[str, Sweep]
    issues: list[Issue]

    def owner(self, node_id: str) -> str | None:
        area = node_id.split("/")[0]
        return area if area in self.sweeps else None


@dataclass
class Radius:
    """Nodes a change reaches: primary nodes, then tiers 1 (family), 2 (related), 3 (inbound related)."""

    primary: list[str]
    hits: dict[str, int]
    owner: str | None
    tiers: dict[int, list[str]]
    why: dict[str, str]
    forced: dict[str, list[str]]
    unmapped: list[str]

    def nodes(self, upto: int) -> list[str]:
        return self.primary + [n for t in range(1, upto + 1) for n in self.tiers.get(t, [])]

    def tier_of(self, node_id: str) -> int | None:
        if node_id in self.primary:
            return 0
        return next((t for t, ids in self.tiers.items() if node_id in ids), None)


