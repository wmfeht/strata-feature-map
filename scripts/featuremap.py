def pr_section(body: str, name: str) -> str:
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    m = re.search(rf"^(#{{1,6}})\s*{re.escape(name)}\s*$", body, re.M | re.I)
    if not m:
        return ""
    end = re.compile(rf"^#{{1,{len(m.group(1))}}}\s", re.M).search(body, m.end())
    return re.sub(r"\n{3,}", "\n\n", body[m.end() : end.start() if end else len(body)]).strip()


def quote(text: str) -> list[str]:
    return [f"> {line}".rstrip() for line in text.splitlines()]


def render_drift(
    repo: str,
    base: str,
    head: str,
    commit_count: int,
    new_prs: list[tuple[dict, Assignment]],
    stale: dict[str, list[dict]],
    tree: Tree,
    scopes: Scopes,
    direct: list[tuple[str, str]],
) -> str:
    out = [
        "# Drift report",
        "",
        f"`{base[:7]}..{head[:7]}` on {repo}: {commit_count} commits, {len(new_prs)} PRs.",
        f"Once processed, set `watermark: {head}` in sources.yaml.",
        "",
        "## Affected features",
    ]
    if not stale:
        out += ["", "None."]
    for node_id in sorted(stale, key=id_key):
        node = tree.nodes[node_id]
        out += ["", f"### `{node_id}` — reviewed at `{node.reviewed_at()[:7]}`"]
        for row in sorted(stale[node_id], key=lambda r: r.get("merged_at") or ""):
            target = assign(tree, scopes, row).node
            placement = "History row here." if target == node_id else (
                f"Touches this feature; its row belongs on `{target}`." if target else "Touches this feature; in triage."
            )
            ref = f"{repo}#{row['number']}"
            out += ["", f"#### {ref} · {row['title']} · {(row.get('merged_at') or '')[:10]}", "", placement]
            if target == node_id:
                for name in ("Description", "How to test"):
                    text = pr_section(row.get("body") or "", name)
                    if text:
                        out += ["", f"**{name}**", ""] + quote(text)
    triage = [(row, a) for row, a in new_prs if a.node is None and not a.reason.startswith("ignored")]
    ignored = [(row, a) for row, a in new_prs if a.reason.startswith("ignored")]
    out += ["", "## Triage", ""]
    out += [
        f"- {repo}#{row['number']} · {row['title']} — {a.reason}. Files: "
        + ", ".join(f"`{f}`" for f in (row.get("files") or [])[:8])
        + (" …" if len(row.get("files") or []) > 8 else "")
        for row, a in triage
    ] or ["None."]
    out += ["", "## Ignored", ""]
    out += [f"- {repo}#{row['number']} · {row['title']}" for row, _ in ignored] or ["None."]
    out += ["", "## Commits without a PR", ""]
    out += [f"- `{sha[:7]}` {subject}" for sha, subject in direct] or ["None."]
    return "\n".join(out) + "\n"


# Commands


def cmd_extract(args: argparse.Namespace) -> int:
    root = args.root
    upstream = load_sources(root)["upstream"]
    rows = load_dataset(root)
    numbers = merged_pr_numbers(upstream["repo"], upstream["branch"])
    todo = numbers if args.refresh else [n for n in numbers if n not in rows]
    collect(root, upstream["repo"], todo, rows)
    print(f"data/prs.jsonl: {len(rows)} PRs ({len(todo)} fetched, {len(numbers)} merged into {upstream['branch']})")
    return 0


def cmd_index(args: argparse.Namespace) -> int:
    written = write_index(args.root)
    print("index: " + (", ".join(written) if written else "up to date"))
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    lister = None if args.offline else Upstream(args.root, load_sources(args.root)).files
    issues = check(args.root, lister)
    for issue in issues:
        print(issue, file=sys.stderr)
    errors = sum(1 for i in issues if i.level == "error")
    print(f"check: {len(load_tree(args.root).nodes)} features, {errors} errors, {len(issues) - errors} warnings")
    return 1 if errors else 0


def cmd_drift(args: argparse.Namespace) -> int:
    root = args.root
    sources = load_sources(root)
    repo = sources["upstream"]["repo"]
    base = args.since or sources.get("watermark")
    if not base:
        raise SystemExit("watermark is not set in sources.yaml; pass --since <sha> for a dry run")
    upstream = Upstream(root, sources)
    head = args.head or upstream.head()
    tree, scopes, dataset = load_tree(root), load_scopes(root), load_dataset(root)
    commits = upstream.log(base, head)
    numbers, direct = [], []
    for sha, subject in commits:
        m = PR_SUBJECT_RE.search(subject)
        if m:
            numbers.append(int(m.group(1) or m.group(2)))
        else:
            direct.append((sha, subject))
    missing = [n for n in numbers if n not in dataset]
    if missing:
        collect(root, repo, missing, dataset)
    new_prs = [(dataset[n], assign(tree, scopes, dataset[n])) for n in sorted(numbers) if n in dataset]
    stale: dict[str, list[dict]] = {}
    ranges: dict[str, set[str]] = {}
    for node_id, node in tree.nodes.items():
        sha = node.reviewed_at()
        if sha is None:
            continue
        if sha not in ranges:
            ranges[sha] = upstream.commits(sha, head)
        rows = [
            row
            for row in dataset.values()
            if row.get("merge_commit") in ranges[sha]
            and any(matches(p, f) for f in row.get("files") or [] for p in node.patterns())
        ]
        if rows:
            stale[node_id] = rows
    report = render_drift(repo, base, head, len(commits), new_prs, stale, tree, scopes, direct)
    if args.out:
        args.out.write_text(report)
    else:
        sys.stdout.write(report)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    extract = sub.add_parser("extract", help="pull merged upstream PRs into data/prs.jsonl")
    extract.add_argument("--refresh", action="store_true", help="refetch PRs already in the dataset")
    sub.add_parser("index", help="regenerate README.md and index/")
    check_cmd = sub.add_parser("check", help="validate the feature tree")
    check_cmd.add_argument("--offline", action="store_true", help="skip the upstream path check")
    drift = sub.add_parser("drift", help="report upstream changes since the watermark")
    drift.add_argument("--since", help="base commit instead of the watermark")
    drift.add_argument("--head", help="head commit instead of upstream's branch head")
    drift.add_argument("--out", type=Path, help="write the report here instead of stdout")
    args = parser.parse_args(argv)
    commands = {"extract": cmd_extract, "index": cmd_index, "check": cmd_check, "drift": cmd_drift}
    return commands[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
